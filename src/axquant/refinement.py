"""Global candidate refinement loop.

Implements top-N plan generation, bounded coordinate descent, beam
refinement, and immutable candidate history tracking.  This module
operates on proxy metrics from sensitivity reports; actual model
evaluation is delegated to the benchmark harness.
"""

